export function resolveServiceCoverTheme(category?: string | null): ServiceCoverTheme {
  const key = (category ?? "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").trim().toLowerCase();
  return Object.hasOwn(serviceCoverThemes, key)
    ? serviceCoverThemes[key as keyof typeof serviceCoverThemes]
    : serviceCoverThemes.generic;
}
